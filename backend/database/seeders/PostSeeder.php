    public function run(): void
    {
        $authorId  = 1;
        $catMap    = Category::pluck('id', 'slug');
        $slugCount = [];

        foreach ($this->posts() as $item) {
            $date  = $item['date'];
            $type  = $item['type'];
            $title = $item['title'];

            $baseSlug = $type . '-' . str_replace('-', '', $date);
            $slugCount[$baseSlug] = ($slugCount[$baseSlug] ?? 0) + 1;
            $slug = $baseSlug . '-' . $slugCount[$baseSlug];

            $post = Post::firstOrCreate(
                ['slug' => $slug],
                [
                    'title'        => $title,
                    'type'         => $type,
                    'content'      => $item['content'] ?? null,
                    'author_id'    => $authorId,
                    'status'       => 'published',
                    'published_at' => $date . ' 09:00:00',
                ]
            );

            if (!empty($item['categories'])) {
                $ids = array_values(array_filter(
                    array_map(fn ($s) => $catMap[$s] ?? null, $item['categories'])
                ));
                $post->categories()->syncWithoutDetaching($ids);
            }
        }
    }

